"""Dataset builder for berkelium-procedural-shapes/1 (Berkelium-owned, MIT).

Produces a frozen manifest (one DatasetRecord per asset), family-level splits with leakage checks, ground-truth
meshes + multiview renders + camera poses for evaluation assets, and a dataset card with content hashes. Training
point samples are generated on the fly from the exact analytic SDF with per-step seeds, so they are reproducible
without storing them.
"""

from __future__ import annotations

import hashlib
import json
import time
from pathlib import Path

import numpy as np

from ..camera import orbit_cameras
from ..contracts import DatasetRecord, sha256_hex
from .geometry import grid_points, mesh_from_sdf_grid, render_mesh, validate_mesh
from .shapes import (
    COLORS,
    GRAMMAR_VERSION,
    RELATIONS,
    SHAPES,
    TEMPLATES,
    Composition,
    colors_at,
    sample_composition,
    sdf,
)

LICENSE = "MIT (Berkelium-owned procedural assets; generated by berkelium_neural.text3d.shapes)"


def all_families() -> list[tuple[str, tuple[str, ...]]]:
    fams = [("single", (s,)) for s in SHAPES]
    fams += [(r, (a, b)) for r in RELATIONS[1:] for a in SHAPES for b in SHAPES]
    return fams


def family_id(rel, shapes) -> str:
    return rel + ":" + "+".join(shapes)


def assign_splits(cfg: dict) -> dict[str, str]:
    """Family -> split. Deterministic given cfg['seed']."""
    rng = np.random.default_rng(cfg["seed"])
    concept = cfg["adapter_concept"]                   # shape withheld from base training (adapter study)
    adapter_test_partners = set(cfg["adapter_test_partners"])
    out, base_pairs = {}, []
    for rel, shapes in all_families():
        fid = family_id(rel, shapes)
        if concept in shapes:
            others = [s for s in shapes if s != concept]
            hard = rel != "single" and (not others or others[0] in adapter_test_partners)
            out[fid] = "adapter_test" if hard else "adapter_train"
        elif rel == "single":
            out[fid] = "train"                         # every base primitive is seen alone in training
        else:
            base_pairs.append(fid)
    order = rng.permutation(len(base_pairs))
    n_test, n_val = cfg["n_test_families"], cfg["n_val_families"]
    for k, i in enumerate(order):
        out[base_pairs[i]] = "test" if k < n_test else "val" if k < n_test + n_val else "train"
    return out


def check_no_leakage(records: list[DatasetRecord]) -> dict:
    fam_split, asset_split = {}, {}
    for r in records:
        if fam_split.setdefault(r.family, r.split) != r.split:
            raise AssertionError(f"family {r.family} appears in {fam_split[r.family]} and {r.split}")
        if asset_split.setdefault(r.asset_sha256, r.split) != r.split:
            raise AssertionError(f"asset {r.asset_sha256[:12]} appears in two splits")
    by = {}
    for r in records:
        by.setdefault(r.split, set()).add(r.family)
    base = set().union(*(by.get(s, set()) for s in ("train", "val", "test")))
    return {"families_per_split": {k: len(v) for k, v in sorted(by.items())}, "family_overlap": 0,
            "asset_overlap": 0, "base_families": len(base)}


def build(cfg: dict, out: Path, log=print) -> dict:
    t0 = time.time()
    out = Path(out)
    (out / "gt").mkdir(parents=True, exist_ok=True)
    (out / "images").mkdir(parents=True, exist_ok=True)
    splits = assign_splits(cfg)
    cams_eval = orbit_cameras(cfg["eval_views"], cfg["camera_radius"], cfg["eval_elevation_deg"],
                              cfg["image_size"], cfg["image_size"], phase_deg=22.5)
    cams_train = orbit_cameras(cfg["train_views"], cfg["camera_radius"], cfg["train_elevation_deg"],
                               cfg["image_size"], cfg["image_size"])
    records, seen = [], set()
    pts = grid_points(cfg["gt_mesh_res"])
    for fi, (rel, shapes) in enumerate(all_families()):
        fid = family_id(rel, shapes)
        split = splits[fid]
        n = cfg["variants"][split]
        rng = np.random.default_rng([cfg["seed"], fi])
        k = 0
        while k < n:
            c = sample_composition(rng, rel, shapes)
            sha = c.asset_sha256()
            if sha in seen:
                continue
            seen.add(sha)
            asset_id = f"{fid.replace(':', '__').replace('+', '_')}__{k:03d}"
            files = {}
            eval_asset = split in ("val", "test", "adapter_test") or k < cfg["pilot_images_per_train_family"]
            cams = cams_eval if split in ("val", "test", "adapter_test") else cams_train
            if eval_asset:
                vol = sdf(c, pts).reshape((cfg["gt_mesh_res"],) * 3)
                v, f = mesh_from_sdf_grid(vol)
                rep = validate_mesh(v, f)
                if not rep["valid"]:
                    raise AssertionError(f"GT mesh invalid for {asset_id}: {rep}")
                np.savez_compressed(out / "gt" / f"{asset_id}.npz", v=v, f=f.astype(np.int32),
                                    c=colors_at(c, v).astype(np.float32), components=rep["components"])
                files["gt_mesh"] = f"gt/{asset_id}.npz"
                from PIL import Image
                col = colors_at(c, v)
                for vi, cam in enumerate(cams):
                    img, _, _ = render_mesh(v, f, col, cam)
                    p = f"images/{asset_id}__v{vi}.png"
                    Image.fromarray((np.clip(img, 0, 1) * 255).round().astype(np.uint8)).save(out / p)
                    files[f"view{vi}"] = p
            records.append(DatasetRecord(
                asset_id=asset_id, family=fid, split=split, license=LICENSE,
                source=f"procedural:{GRAMMAR_VERSION}:seed={cfg['seed']}:family={fi}:variant={k}",
                asset_sha256=sha, caption=c.caption(),
                caption_provenance=f"template:{rel}:{c.template}:{TEMPLATES[rel][c.template]}",
                cameras=tuple(cams) if eval_asset else (), files=files,
                attributes={"composition": c.canonical(),
                            "gt_components": rep["components"] if eval_asset else None}))
            k += 1
        log(f"  {fid:28s} {split:13s} {n} variants")
    leak = check_no_leakage(records)
    man_path = out / "manifest.jsonl"
    man_path.write_text("".join(r.model_dump_json() + "\n" for r in records))
    split_hashes = {s: hashlib.sha256("".join(sorted(r.asset_sha256 for r in records if r.split == s)).encode())
                    .hexdigest() for s in sorted({r.split for r in records})}
    files_hash = hashlib.sha256()
    for p in sorted(out.rglob("*")):
        if p.is_file() and p.name not in ("dataset_card.json",):
            files_hash.update(p.relative_to(out).as_posix().encode())
            files_hash.update(sha256_hex(p.read_bytes()).encode())
    card = {"dataset": cfg["name"], "grammar": GRAMMAR_VERSION, "license": LICENSE, "config": cfg,
            "n_assets": len(records), "counts": {s: sum(r.split == s for r in records) for s in split_hashes},
            "leakage_check": leak, "split_hashes": split_hashes, "manifest_sha256": sha256_hex(man_path.read_bytes()),
            "files_sha256": files_hash.hexdigest(), "vocabulary": {"shapes": list(SHAPES), "colors": list(COLORS),
            "relations": list(RELATIONS)}, "camera_convention": "OpenCV, T_cw world->camera, +Y-up world",
            "units": "normalized_object", "build_seconds": round(time.time() - t0, 1)}
    (out / "dataset_card.json").write_text(json.dumps(card, indent=2))
    return card


def load_manifest(root: Path, splits=None) -> list[DatasetRecord]:
    recs = [DatasetRecord.model_validate_json(x) for x in (Path(root) / "manifest.jsonl").read_text().splitlines() if x]
    return [r for r in recs if splits is None or r.split in splits]


def composition_of(r: DatasetRecord) -> Composition:
    from .shapes import Part
    c = dict(r.attributes["composition"])
    c.pop("grammar")
    parts = tuple(Part(p["shape"], p["color"], p["size"], tuple(p["dims"])) for p in c["parts"])
    return Composition(c["relation"], parts, c["template"])
