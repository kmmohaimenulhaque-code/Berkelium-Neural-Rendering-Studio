"""Berkelium-owned procedural shape grammar with exact analytic ground truth.

Every asset is generated by this file from a seed, so its license is the repository's (MIT, Berkelium-owned) and its
geometry has an independent ground truth (signed distance field), which is what makes geometric metrics
(Chamfer, normal consistency, F-score) meaningful. Units: ``normalized_object`` (bounding box max extent 1.6,
centred), never metres.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass

import numpy as np

GRAMMAR_VERSION = "berkelium-procedural-shapes/1"
SHAPES = ("sphere", "box", "cylinder", "cone", "torus", "capsule")
COLORS = {"red": (0.85, 0.12, 0.10), "green": (0.10, 0.65, 0.20), "blue": (0.12, 0.25, 0.85),
          "yellow": (0.95, 0.85, 0.10), "orange": (0.95, 0.50, 0.08), "purple": (0.55, 0.15, 0.70),
          "white": (0.92, 0.92, 0.92), "cyan": (0.10, 0.80, 0.85)}
SIZES = {"small": 0.7, "": 1.0, "large": 1.3}
RELATIONS = ("single", "on_top_of", "next_to")
EXTENT = 1.6
GAP = 0.2   # next_to separation (pre-normalisation units) -> two connected components

# caption templates; provenance = template id. {A}/{B} expand to "[size ]color shape".
TEMPLATES = {
    "single": ["a {A}", "one {A}", "{A}"],
    "on_top_of": ["a {A} on top of a {B}", "a {A} stacked on a {B}", "a {B} with a {A} on top"],
    "next_to": ["a {A} next to a {B}", "a {A} beside a {B}", "a {A} to the left of a {B}"],
}


@dataclass(frozen=True)
class Part:
    shape: str
    color: str
    size: str
    dims: tuple[float, float, float]      # shape-specific half extents before placement


@dataclass(frozen=True)
class Composition:
    relation: str
    parts: tuple[Part, ...]               # (A,) or (A, B); A is the top / left part
    template: int

    @property
    def family(self) -> str:
        """Asset family = structure (relation + ordered shapes). All colour/size/paraphrase variants of a
        structure share a family, so they can never be split across train and test."""
        return self.relation + ":" + "+".join(p.shape for p in self.parts)

    def caption(self) -> str:
        def np_(p):
            return " ".join(w for w in (p.size, p.color, p.shape) if w)
        t = TEMPLATES[self.relation][self.template]
        return t.format(A=np_(self.parts[0]), B=np_(self.parts[1]) if len(self.parts) > 1 else "")

    def canonical(self) -> dict:
        return {"grammar": GRAMMAR_VERSION, **asdict(self)}

    def asset_sha256(self) -> str:
        """Asset identity: hash of the canonical generator parameters (geometry + colours; NOT the caption template,
        which is a paraphrase of the same asset)."""
        c = self.canonical()
        c.pop("template")
        return hashlib.sha256(json.dumps(c, sort_keys=True).encode()).hexdigest()


def _part_dims(shape: str, size: str, rng: np.random.Generator) -> tuple[float, float, float]:
    s = SIZES[size] * rng.uniform(0.9, 1.1)
    if shape == "sphere":
        r = 0.5 * s
        return (r, r, r)
    if shape == "box":
        return tuple(float(v) for v in 0.45 * s * rng.uniform(0.75, 1.25, 3))
    if shape in ("cylinder", "cone", "capsule"):
        return (0.4 * s * rng.uniform(0.85, 1.15), 0.5 * s * rng.uniform(0.85, 1.25), 0.0)  # (radius, half-height)
    if shape == "torus":
        R = 0.45 * s * rng.uniform(0.9, 1.1)
        return (R, 0.16 * s * rng.uniform(0.85, 1.15), 0.0)                              # (major, minor)
    raise ValueError(shape)


def half_height(p: Part) -> float:
    if p.shape in ("sphere", "box"):
        return p.dims[1]
    if p.shape == "torus":
        return p.dims[1]
    if p.shape == "capsule":
        return p.dims[1] + p.dims[0]
    return p.dims[1]


def half_width(p: Part) -> float:
    if p.shape == "box":
        return p.dims[0]
    if p.shape == "torus":
        return p.dims[0] + p.dims[1]
    return p.dims[0]


def sample_composition(rng: np.random.Generator, relation: str, shapes: tuple[str, ...], template: int | None = None,
                       colors: tuple[str, ...] | None = None) -> Composition:
    n = 1 if relation == "single" else 2
    cols = colors or tuple(rng.choice(list(COLORS), size=n, replace=n > len(COLORS)))
    sizes = ("",) if n == 1 else tuple(rng.choice(list(SIZES), size=2))
    parts = tuple(Part(s, str(c), str(z), _part_dims(s, z, rng)) for s, c, z in zip(shapes, cols, sizes, strict=True))
    t = int(rng.integers(len(TEMPLATES[relation]))) if template is None else template
    return Composition(relation, parts, t)


# ------------------------------------------------------------------------------------------- placement
def placements(c: Composition) -> tuple[list[np.ndarray], float]:
    """World centres of each part and the normalisation scale (pre-normalisation coordinates)."""
    if c.relation == "single":
        centers = [np.zeros(3)]
    elif c.relation == "on_top_of":
        a, b = c.parts
        hb, ha = half_height(b), half_height(a)
        centers = [np.array([0.0, hb, 0.0]), np.array([0.0, -ha, 0.0])]          # A above B, touching at y=0
    else:
        a, b = c.parts
        wa, wb = half_width(a), half_width(b)
        centers = [np.array([-(wa + GAP / 2), 0.0, 0.0]), np.array([wb + GAP / 2, 0.0, 0.0])]
    lo, hi = np.full(3, np.inf), np.full(3, -np.inf)
    for p, ctr in zip(c.parts, centers, strict=True):
        e = np.array([half_width(p), half_height(p), half_width(p) if p.shape != "box" else p.dims[2]])
        lo, hi = np.minimum(lo, ctr - e), np.maximum(hi, ctr + e)
    mid = (lo + hi) / 2
    scale = EXTENT / float((hi - lo).max())
    return [(ctr - mid) for ctr in centers], scale


def _sdf_part(p: Part, q: np.ndarray) -> np.ndarray:
    """Exact SDF of a primitive centred at the origin, Y-up axis. q: [M,3]."""
    x, y, z = q[:, 0], q[:, 1], q[:, 2]
    if p.shape == "sphere":
        return np.linalg.norm(q, axis=1) - p.dims[0]
    if p.shape == "box":
        d = np.abs(q) - np.array(p.dims)
        return np.linalg.norm(np.maximum(d, 0), axis=1) + np.minimum(d.max(1), 0)
    if p.shape == "cylinder":
        r, h = p.dims[0], p.dims[1]
        d = np.stack([np.hypot(x, z) - r, np.abs(y) - h], 1)
        return np.minimum(d.max(1), 0) + np.linalg.norm(np.maximum(d, 0), axis=1)
    if p.shape == "capsule":
        r, h = p.dims[0], p.dims[1]
        yy = np.clip(y, -h, h)
        return np.sqrt(x * x + (y - yy) ** 2 + z * z) - r
    if p.shape == "torus":
        R, r = p.dims[0], p.dims[1]
        return np.hypot(np.hypot(x, z) - R, y) - r
    if p.shape == "cone":   # exact capped cone, base radius r at y=-h, apex (radius 0) at y=+h
        r1, h = p.dims[0], p.dims[1]
        qx, qy = np.hypot(x, z), y
        k1 = np.array([0.0, h])
        k2 = np.array([-r1, 2.0 * h])
        ca = np.stack([qx - np.minimum(qx, np.where(qy < 0, r1, 0.0)), np.abs(qy) - h], 1)
        pq = np.stack([qx, qy], 1)
        t = np.clip(((k1[None] - pq) @ k2) / (k2 @ k2), 0.0, 1.0)
        cb = pq - k1[None] + k2[None] * t[:, None]
        s = np.where((cb[:, 0] < 0) & (ca[:, 1] < 0), -1.0, 1.0)
        return s * np.sqrt(np.minimum((ca * ca).sum(1), (cb * cb).sum(1)))
    raise ValueError(p.shape)


def sdf(c: Composition, pts: np.ndarray, return_part: bool = False):
    """Exact union SDF of the normalised composition at points ``pts`` [M,3] (normalized_object units)."""
    centers, scale = placements(c)
    q0 = pts / scale
    ds = np.stack([_sdf_part(p, q0 - ctr) for p, ctr in zip(c.parts, centers, strict=True)], 1) * scale
    d = ds.min(1)
    return (d, ds.argmin(1)) if return_part else d


def colors_at(c: Composition, pts: np.ndarray) -> np.ndarray:
    _, idx = sdf(c, pts, return_part=True)
    pal = np.array([COLORS[p.color] for p in c.parts])
    return pal[idx]
